'use strict';

const crypto = require('node:crypto');
const jwt = require('jsonwebtoken');
const { google } = require('googleapis');
const MailComposer = require('nodemailer/lib/mail-composer');
const { UserMailboxConnection, User } = require('../../models');
const { env } = require('../../core/config/env');
const { encryptJson, decryptJson } = require('../../core/security/secretBox');
const { recordAudit } = require('../../core/audit/auditService');

/**
 * Sending sales email from each person's own Google Workspace mailbox
 * (ADR 0015). One OAuth client for Leadzaro; each employee connects their
 * own mailbox once. Only the gmail.send scope (plus openid/email to learn
 * which address was connected) is requested — Leadzaro can send as them
 * but can't read their mail. The refresh token is stored encrypted and
 * never leaves the server. The sender is always the logged-in person's
 * own connection; there is no fallback to a shared account.
 */

const SCOPES = ['https://www.googleapis.com/auth/gmail.send', 'openid', 'email'];
const SEND_SCOPE = SCOPES[0];
const CALLBACK_PATH = '/api/v1/integrations/gmail/callback';
const STATE_COOKIE = 'lz_gmail_oauth';
const STATE_PURPOSE = 'gmail_connect';

function invalid(message, statusCode = 422) {
  const err = new Error(message);
  err.statusCode = statusCode;
  return err;
}

function configured() {
  return Boolean(env.GOOGLE_OAUTH_CLIENT_ID && env.GOOGLE_OAUTH_CLIENT_SECRET);
}

/** Must match an "Authorized redirect URI" on the Google OAuth client exactly. */
function redirectUri() {
  if (env.GOOGLE_OAUTH_REDIRECT_URI) return env.GOOGLE_OAUTH_REDIRECT_URI;
  const base = env.PUBLIC_API_BASE_URL || (env.IS_PRODUCTION ? env.APP_BASE_URL : `http://localhost:${env.PORT}`);
  return `${String(base).replace(/\/$/, '')}${CALLBACK_PATH}`;
}

function oauthClient() {
  return new google.auth.OAuth2(env.GOOGLE_OAUTH_CLIENT_ID, env.GOOGLE_OAUTH_CLIENT_SECRET, redirectUri());
}

function tokenContext(userId, agencyId) {
  return `${userId}:${agencyId}:gmail`;
}

/** Where the browser lands after Google sends the person back. */
function settingsUrl(result) {
  const query = new URLSearchParams(result).toString();
  return `${env.APP_BASE_URL.replace(/\/$/, '')}/app/settings/account?${query}#email-sending`;
}

async function findConnection(userId, agencyId) {
  return UserMailboxConnection.findOne({ where: { userId, agencyOrganizationId: agencyId, provider: 'gmail' } });
}

function present(connection) {
  return {
    configured: configured(),
    connected: Boolean(connection && connection.status === 'connected'),
    needsReconnect: Boolean(connection && connection.status === 'error'),
    email: connection?.email || null,
    connectedAt: connection?.connectedAt || null,
    lastUsedAt: connection?.lastUsedAt || null,
    lastError: connection?.status === 'error' ? connection.lastErrorMessage : null,
  };
}

async function status(ctx) {
  return present(await findConnection(ctx.userId, ctx.agencyId));
}

/**
 * Starts the Google consent flow for the signed-in person. The state is a
 * short-lived signed token naming this person; a matching random nonce is
 * also set as an httpOnly cookie, so a consent link generated by someone
 * else can't attach a mailbox to their account.
 */
async function startConnect(ctx) {
  if (!configured()) throw invalid('Gmail sending isn’t set up on this server yet (GOOGLE_OAUTH_CLIENT_ID / GOOGLE_OAUTH_CLIENT_SECRET).', 503);
  const nonce = crypto.randomBytes(16).toString('hex');
  const state = jwt.sign({
    purpose: STATE_PURPOSE, uid: ctx.userId, aid: ctx.agencyId, nonce,
  }, env.ACCESS_TOKEN_SECRET, { expiresIn: '10m' });
  const user = await User.findByPk(ctx.userId, { attributes: ['email'] });
  const url = oauthClient().generateAuthUrl({
    access_type: 'offline',
    prompt: 'consent', // always return a refresh token, even on reconnect
    scope: SCOPES,
    state,
    include_granted_scopes: false,
    login_hint: user?.email || undefined,
  });
  return { url, nonce };
}

function stateCookieOptions() {
  return {
    httpOnly: true, sameSite: 'lax', secure: env.IS_PRODUCTION, path: '/api/v1/integrations/gmail', maxAge: 10 * 60 * 1000,
  };
}

/**
 * Google redirects here with ?code&state (or ?error). Returns the settings
 * URL to send the browser to, with a plain result for the page to show.
 */
async function handleCallback({ code, state, error }, cookieNonce) {
  if (error) return settingsUrl({ gmail: 'error', reason: error === 'access_denied' ? 'You didn’t allow access, so nothing was connected.' : `Google said: ${String(error).slice(0, 80)}` });
  let claims;
  try {
    claims = jwt.verify(String(state || ''), env.ACCESS_TOKEN_SECRET);
  } catch {
    return settingsUrl({ gmail: 'error', reason: 'That connection link expired. Start again from Settings.' });
  }
  if (claims.purpose !== STATE_PURPOSE || !cookieNonce || claims.nonce !== cookieNonce) {
    return settingsUrl({ gmail: 'error', reason: 'Start the connection from your own Settings page in this browser.' });
  }
  if (!code) return settingsUrl({ gmail: 'error', reason: 'Google didn’t return an authorization code.' });

  const client = oauthClient();
  let tokens;
  try {
    ({ tokens } = await client.getToken(String(code)));
  } catch {
    return settingsUrl({ gmail: 'error', reason: 'Google wouldn’t complete the connection. Try again.' });
  }
  const granted = String(tokens.scope || '').split(/\s+/);
  if (!granted.includes(SEND_SCOPE)) return settingsUrl({ gmail: 'error', reason: 'Permission to send email wasn’t granted. Tick the Gmail box on Google’s screen.' });
  if (!tokens.refresh_token) return settingsUrl({ gmail: 'error', reason: 'Google didn’t return a lasting connection. Try again.' });

  let email;
  try {
    const ticket = await client.verifyIdToken({ idToken: tokens.id_token, audience: env.GOOGLE_OAUTH_CLIENT_ID });
    const payload = ticket.getPayload();
    if (!payload?.email || payload.email_verified === false) throw new Error('unverified');
    email = payload.email.toLowerCase();
  } catch {
    return settingsUrl({ gmail: 'error', reason: 'Couldn’t confirm which Google account was connected.' });
  }

  const ciphertext = encryptJson({ refreshToken: tokens.refresh_token }, tokenContext(claims.uid, claims.aid));
  const existing = await findConnection(claims.uid, claims.aid);
  const values = {
    email, scopes: granted.join(' '), status: 'connected', refreshTokenCiphertext: ciphertext, connectedAt: new Date(), lastErrorMessage: null, lastErrorAt: null,
  };
  if (existing) await existing.update(values);
  else {
    await UserMailboxConnection.create({
      ...values, userId: claims.uid, agencyOrganizationId: claims.aid, provider: 'gmail',
    });
  }
  await recordAudit({
    organizationId: claims.aid, actorUserId: claims.uid, action: 'mailbox.connected', targetType: 'User', targetId: claims.uid, metadata: { provider: 'gmail', email },
  });
  return settingsUrl({ gmail: 'connected', email });
}

async function disconnect(ctx) {
  const connection = await findConnection(ctx.userId, ctx.agencyId);
  if (!connection) return present(null);
  try {
    const { refreshToken } = decryptJson(connection.refreshTokenCiphertext, tokenContext(ctx.userId, ctx.agencyId));
    await oauthClient().revokeToken(refreshToken);
  } catch {
    // Already revoked or unreadable — removing our copy is what matters.
  }
  await connection.destroy();
  await recordAudit({
    organizationId: ctx.agencyId, actorUserId: ctx.userId, action: 'mailbox.disconnected', targetType: 'User', targetId: ctx.userId, metadata: { provider: 'gmail' }, req: ctx.req,
  });
  return present(null);
}

function buildRaw(message) {
  return new Promise((resolve, reject) => {
    new MailComposer(message).compile().build((err, buffer) => (err ? reject(err) : resolve(buffer.toString('base64url'))));
  });
}

/**
 * Sends as the given person through their own mailbox. Never throws for
 * a delivery problem — returns { ok, error, reconnect } so the caller
 * records exactly what happened. A revoked/expired grant marks the
 * connection as needing a reconnect.
 */
async function sendAs({
  userId, agencyId, fromName, to, subject, text, headers,
}) {
  const connection = await findConnection(userId, agencyId);
  if (!connection || connection.status !== 'connected') {
    return { ok: false, reconnect: true, error: connection ? 'Your Gmail connection needs to be reconnected (Settings → My account).' : 'Connect your Gmail in Settings → My account to send from Leadzaro.' };
  }
  let refreshToken;
  try {
    ({ refreshToken } = decryptJson(connection.refreshTokenCiphertext, tokenContext(userId, agencyId)));
  } catch {
    await connection.update({ status: 'error', lastErrorMessage: 'The saved connection can no longer be read. Reconnect Gmail.', lastErrorAt: new Date() });
    return { ok: false, reconnect: true, error: 'Your Gmail connection needs to be reconnected (Settings → My account).' };
  }
  const client = oauthClient();
  client.setCredentials({ refresh_token: refreshToken });
  const safeName = String(fromName || '').replace(/["<>\r\n]/g, '').trim();
  try {
    const raw = await buildRaw({
      from: safeName ? `"${safeName}" <${connection.email}>` : connection.email, to, subject, text, headers,
    });
    const res = await google.gmail({ version: 'v1', auth: client }).users.messages.send({ userId: 'me', requestBody: { raw } });
    await connection.update({ lastUsedAt: new Date() });
    return {
      ok: true, providerMessageId: res.data.id || null, from: connection.email, provider: 'gmail',
    };
  } catch (err) {
    const reason = err?.response?.data?.error;
    const revoked = reason === 'invalid_grant' || err?.code === 401 || err?.response?.status === 401;
    if (revoked) {
      await connection.update({ status: 'error', lastErrorMessage: 'Google rejected the saved connection (it was revoked or expired). Reconnect Gmail.', lastErrorAt: new Date() });
      return { ok: false, reconnect: true, error: 'Your Gmail connection was revoked or expired. Reconnect it in Settings → My account.' };
    }
    const message = err?.response?.data?.error?.message || err?.message || 'Gmail did not accept the message.';
    await connection.update({ lastErrorMessage: String(message).slice(0, 500), lastErrorAt: new Date() });
    return { ok: false, error: `Gmail: ${String(message).slice(0, 200)}` };
  }
}

module.exports = {
  configured, redirectUri, status, startConnect, handleCallback, disconnect, sendAs, findConnection, stateCookieOptions, STATE_COOKIE,
};
